# ------------------------- HTTP СЕРВЕР (ТОЛЬКО API) -------------------------
class ChristineWebHandler(http.server.SimpleHTTPRequestHandler):
    engine = None  # Инициализируется методом start_server()

    def end_headers(self):
        # Добавляем заголовки для CORS, чтобы браузер не блокировал Fetch-запросы
        self.send_header('Access-Control-Allow-Origin', '*')
        self.send_header('Access-Control-Allow-Methods', 'GET, POST, OPTIONS')
        self.send_header('Access-Control-Allow-Headers', 'Content-Type')
        super().end_headers()

    def do_OPTIONS(self):
        self.send_response(200)
        self.end_headers()

    def do_GET(self):
        global ALL_SCENES
        global player_stats

        # 1. API отдачи скомпилированной пиксельной графики NumPy
        if self.path == '/api/matrix':
            self.send_response(200)
            self.send_header('Access-Control-Allow-Origin', '*')
            self.send_header('Content-Type', 'application/json')
            self.end_headers()
            
            # Больше никакой инжекции полосок в матрицу! Отдаём чистую графику.
            # Браузер сам заберёт актуальные цифры параметров из этого пакета:
            response = {
                "scenes": ALL_SCENES, 
                "stats": player_stats
            }
            self.wfile.write(json.dumps(response).encode('utf-8'))
            return

        # 2. API получения текущего состояния (Синхронный старт текста и сцены)
        elif self.path == '/api/state':
            self.send_response(200)
            self.send_header('Access-Control-Allow-Origin', '*')
            self.send_header('Content-Type', 'application/json; charset=utf-8')
            self.end_headers()

            # Считываем данные строго ТЕКУЩЕЙ активной сцены, на которой стоит движок!
            current_idx = self.engine.current_scene
            scene_data = self.engine.storyboard.get(current_idx)

            state = {
                "stats": {
                    "repair": self.engine.repair,
                    "sanity": self.engine.sanity,
                    "fuel": self.engine.fuel,
                    "reputation": self.engine.reputation
                },
                "currentScene": current_idx,
                "gameActive": self.engine.game_active,
                "intro": scene_data.intro if scene_data else "Конец маршрута.",
                "expected": scene_data.expected if scene_data else []
            }
            self.wfile.write(json.dumps(state, ensure_ascii=False).encode('utf-8'))
            return

        else:
            # Раздача статики (HTML, JS, CSS)
            super().do_GET()

    def do_POST(self):
        if self.path == '/api/command':
            length = int(self.headers.get('Content-Length', 0))
            body = self.rfile.read(length)
            try:
                data = json.loads(body.decode('utf-8'))
                cmd = data.get('command', '')
                result = self.engine.process_command(cmd)
                self.send_response(200)
                self.send_header('Content-Type', 'application/json; charset=utf-8')
                self.end_headers()
                self.wfile.write(json.dumps(result, ensure_ascii=False).encode('utf-8'))
            except Exception as e:
                self.send_response(500)
                self.end_headers()
                print(f"[ОШИБКА POST]: {e}")
        else:
            self.send_response(404)
            self.end_headers()

def start_server():
    PORT = 8000
    handler = ChristineWebHandler
    storyboard = get_quest_storyboard()
    
    # СИНХРОНИЗАЦИЯ: Явно связываем единственный экземпляр ядра игры с веб-сервером
    handler.engine = GameEngine(storyboard)
    
    # Позволяет мгновенно перезапускать скрипт в консоли Linux/Windows без зависания порта 8000
    socketserver.TCPServer.allow_reuse_address = True
    
    with socketserver.TCPServer(("", PORT), handler) as httpd:
        print(f"\n[КРИСТИНА] Демонический сервер запущен на http://localhost:{PORT}")
        print("Нажмите Ctrl+C для остановки")
        
        # Автоматически открываем графический фронтенд игры в браузере по умолчанию
        webbrowser.open(f"http://localhost:{PORT}/")
        httpd.serve_forever()

