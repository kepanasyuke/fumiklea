                if f_idx >= 15:
                    # Черная зигзагообразная ломаная линия трещины прямо над фарой
                    frame[cy+4, cx+5:cx+9] = C['BLK']
                    frame[cy+5, cx+8:cx+12] = C['BLK']
                    frame[cy+6, cx+11:cx+14] = C['BLK']

                # Хромированный молдинг-стрела борта Кристины
