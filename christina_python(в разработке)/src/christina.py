                    grille_progress = (f_idx - 15)
                    for gi in range(3):
                        drop_x = int(15 - grille_progress * 1.3 - gi * 2)
                        drop_y = int(cy + 14 + grille_progress * 0.4)
                        if 0 <= drop_x < WIDTH and 21 <= drop_y <= 25:
                            frame[drop_y, drop_x] = C['WHT'] # Осколки ломаной белой решетки на дороге

