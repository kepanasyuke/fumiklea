                #  СИСТЕМНЫЙ БЛОК: ГИГАНТСКАЯ ФАРА ЛОПАЕТСЯ В ВЫЖЖЕННУЮ ДЫРУ (С 15 КАДРА)
                # --------------------------------------------------------------------
                fx = 7 + shake_x
                fy = 3 + shake_y

