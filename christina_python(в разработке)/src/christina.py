                        if y_buddy < cy + 6:              frame[y_buddy, x_buddy] = C['BLU']
                        elif cy + 6 <= y_buddy < cy + 12: frame[y_buddy, x_buddy] = C['C_BUDDY_BLUE']
                        else:                             frame[y_buddy, x_buddy] = C['BLK']

